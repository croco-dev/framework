import type { PageExperienceInput, PageExperienceRow } from "@croco/metrics-core";
export const at = (s: number) => new Date(Date.UTC(2026, 0, 1) + s * 1000).toISOString();
const row = (
  kind: PageExperienceRow["kind"],
  session: string,
  s: number,
  value: string = kind,
): PageExperienceRow => ({
  id: `${session}-${kind}`,
  source: kind === "committed" ? "billing" : "browser",
  kind,
  session,
  subject: session,
  pageInstance: `p-${session}`,
  page: "product",
  occurredAt: at(s),
  receivedAt: at(s),
  value,
});
