import { readFileSync, writeFileSync } from "node:fs";
import { compileDiGraph, writeDiGraph } from "@croco/esbuild-plugin";
import { compileCloudflareCrons } from "@croco/preset-cloudflare/scheduled";
import { parse } from "smol-toml";
import { ProblemFactory } from "@croco/problems-core";
import { workerDiOptions } from "../worker.di.config";

async function main() {
  writeDiGraph(compileDiGraph({ baseDir: process.cwd(), ...workerDiOptions }));
  const { generatedDiGraph } = await import("../.croco/worker-di.generated");
  const manifest = compileCloudflareCrons(generatedDiGraph);
  const manifestFile = "worker-crons.manifest.json";
  const declaration = {
    schemaVersion: manifest.schemaVersion,
    crons: manifest.crons,
    bindings: manifest.bindings,
  };
  const source = `// Generated by worker:crons:write.\nexport const workerCronManifest = ${JSON.stringify(manifest, null, 2)} as const;\n`;
  const configFile = "wrangler.toml";
  const config = readFileSync(configFile, "utf8");
  const parsed = parse(config);
  const triggers = parsed.triggers as { crons?: unknown } | undefined;
  if (process.argv.includes("--write")) {
    if (!/# croco-crons:start\n[\s\S]*?# croco-crons:end/.test(config)) {
      throw ProblemFactory.badRequest(
        "CLOUDFLARE_CRON_CONFIG_INVALID",
        "Missing Croco Cron ownership markers in wrangler.toml.",
      );
    }
    writeFileSync(manifestFile, `${JSON.stringify(declaration, null, 2)}\n`);
    writeFileSync(
      configFile,
      config.replace(
        /# croco-crons:start\n[\s\S]*?# croco-crons:end/,
        `# croco-crons:start\n[triggers]\ncrons = ${JSON.stringify(manifest.crons)}\n# croco-crons:end`,
      ),
    );
  } else if (
    JSON.stringify(JSON.parse(readFileSync(manifestFile, "utf8"))) !==
      JSON.stringify(declaration) ||
    JSON.stringify(triggers?.crons) !== JSON.stringify(manifest.crons)
  ) {
    throw ProblemFactory.badRequest(
      "CLOUDFLARE_CRON_OUTPUT_DRIFT",
      "Run pnpm worker:crons:write and review the output.",
    );
  }
  writeFileSync(".croco/worker-crons.generated.ts", source);
}

void main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
