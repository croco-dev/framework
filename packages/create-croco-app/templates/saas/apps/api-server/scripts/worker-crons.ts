import { readFileSync, writeFileSync } from "node:fs";
import { compileDiGraph, writeDiGraph } from "@croco/esbuild-plugin";
import type { CloudflareCronManifest } from "@croco/preset-cloudflare/scheduled";
import { parse } from "smol-toml";
import { ProblemFactory } from "@croco/problems-core";
import { unstable_dev } from "wrangler";
import { workerDiOptions } from "../worker.di.config";

/** Read decorators in workerd without initializing the application or invoking its providers. */
async function collectManifest(config: ReturnType<typeof parse>): Promise<CloudflareCronManifest> {
  const entry = ".croco/worker-crons.inspect.ts";
  const toolingConfig = ".croco/worker-crons.inspect.toml";
  writeFileSync(
    entry,
    `
    import { generatedDiGraph } from './worker-di.generated';
    import { compileCloudflareCrons } from '@croco/preset-cloudflare/scheduled';
    import { Problem } from '@croco/problems-core';
    export default {
      fetch() {
        try {
          return Response.json({ manifest: compileCloudflareCrons(generatedDiGraph) });
        } catch (error) {
          if (error instanceof Problem) return Response.json({ problem: error.toJSON() }, { status: 400 });
          throw error;
        }
      }
    };
  `,
  );
  writeFileSync(
    toolingConfig,
    [
      'name = "croco-cron-metadata"',
      `compatibility_date = ${JSON.stringify(config.compatibility_date)}`,
      `compatibility_flags = ${JSON.stringify(config.compatibility_flags ?? [])}`,
    ].join("\n"),
  );
  // A separate local configuration never attaches application resources, secrets or remote bindings.
  const worker = await unstable_dev(entry, {
    config: toolingConfig,
    local: true,
    persist: false,
    logLevel: "error",
    experimental: {
      forceLocal: true,
      disableExperimentalWarning: true,
      disableDevRegistry: true,
      watch: false,
    },
  });
  try {
    const response = await worker.fetch("http://metadata.local");
    const result = (await response.json()) as {
      manifest?: CloudflareCronManifest;
      problem?: { code: string; detail?: string };
    };
    if (!response.ok || !result.manifest) {
      throw ProblemFactory.badRequest(
        result.problem?.code ?? "CLOUDFLARE_CRON_CONFIG_INVALID",
        result.problem?.detail ?? "Unable to collect Worker Cron metadata.",
      );
    }
    return result.manifest;
  } finally {
    await worker.stop();
  }
}

/** Refuse named-environment overrides that would deploy schedules absent from this graph. */
function validateEnvironments(config: ReturnType<typeof parse>, manifest: CloudflareCronManifest) {
  const environments = config.env as Record<string, { triggers?: { crons?: unknown } }> | undefined;
  for (const [name, environment] of Object.entries(environments ?? {})) {
    if (
      environment.triggers !== undefined &&
      JSON.stringify(environment.triggers?.crons) !== JSON.stringify(manifest.crons)
    ) {
      throw ProblemFactory.badRequest(
        "CLOUDFLARE_CRON_OUTPUT_DRIFT",
        `Wrangler environment '${name}' overrides the compiled Cron schedules.`,
      );
    }
  }
}

/** Write reviewed declarations or check both their manifest and effective Wrangler schedules. */
async function main() {
  const configFile = "wrangler.toml";
  const config = readFileSync(configFile, "utf8");
  const parsed = parse(config);
  writeDiGraph(compileDiGraph({ baseDir: process.cwd(), ...workerDiOptions }));
  const manifest = await collectManifest(parsed);
  validateEnvironments(parsed, manifest);
  const manifestFile = "worker-crons.manifest.json";
  const declaration = {
    schemaVersion: manifest.schemaVersion,
    crons: manifest.crons,
    bindings: manifest.bindings,
  };
  const source = `// Generated by worker:crons:write.\nexport const workerCronManifest = ${JSON.stringify(manifest, null, 2)} as const;\n`;
  const triggers = parsed.triggers as { crons?: unknown } | undefined;
  if (process.argv.includes("--write")) {
    const ownedBlock = /# croco-crons:start(\r?\n)[\s\S]*?# croco-crons:end/.exec(config);
    if (!ownedBlock) {
      throw ProblemFactory.badRequest(
        "CLOUDFLARE_CRON_CONFIG_INVALID",
        "Missing Croco Cron ownership markers in wrangler.toml.",
      );
    }
    writeFileSync(manifestFile, `${JSON.stringify(declaration, null, 2)}\n`);
    writeFileSync(
      configFile,
      config.replace(
        ownedBlock[0],
        [
          "# croco-crons:start",
          "[triggers]",
          `crons = ${JSON.stringify(manifest.crons)}`,
          "# croco-crons:end",
        ].join(ownedBlock[1]),
      ),
    );
  } else if (
    JSON.stringify(JSON.parse(readFileSync(manifestFile, "utf8"))) !==
      JSON.stringify(declaration) ||
    JSON.stringify(triggers?.crons) !== JSON.stringify(manifest.crons)
  ) {
    throw ProblemFactory.badRequest(
      "CLOUDFLARE_CRON_OUTPUT_DRIFT",
      "Run pnpm worker:crons:write and review the output.",
    );
  }
  writeFileSync(".croco/worker-crons.generated.ts", source);
}

void main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
