export function renderDemoMemberHtml(userId: string, role: string): string {
  return `<p>${escapeHtml(userId)} joined as ${escapeHtml(role)}.</p>`;
}

function escapeHtml(value: string): string {
  return value.replace(/[&<>"']/g, (character) => {
    switch (character) {
      case "&":
        return "&amp;";
      case "<":
        return "&lt;";
      case ">":
        return "&gt;";
      case '"':
        return "&quot;";
      case "'":
        return "&#39;";
      default:
        return character;
    }
  });
}
