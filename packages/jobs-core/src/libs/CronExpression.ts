/**
 * 자주 사용하는 Cron 표현식 상수
 *
 * 6필드 형식 (초 분 시 일 월 요일)
 * - 초: 0-59
 * - 분: 0-59
 * - 시: 0-23
 * - 일: 1-31
 * - 월: 1-12
 * - 요일: 0-6 (0=일요일)
 */
export enum CronExpression {
  /** 매초 실행 */
  EVERY_SECOND = '* * * * * *',

  /** 5초마다 실행 */
  EVERY_5_SECONDS = '*/5 * * * * *',

  /** 10초마다 실행 */
  EVERY_10_SECONDS = '*/10 * * * * *',

  /** 30초마다 실행 */
  EVERY_30_SECONDS = '*/30 * * * * *',

  /** 매분 실행 */
  EVERY_MINUTE = '* * * * *',

  /** 5분마다 실행 */
  EVERY_5_MINUTES = '*/5 * * * *',

  /** 10분마다 실행 */
  EVERY_10_MINUTES = '*/10 * * * *',

  /** 30분마다 실행 */
  EVERY_30_MINUTES = '*/30 * * * *',

  /** 매시 정각 실행 */
  EVERY_HOUR = '0 * * * *',

  /** 매일 자정 (00:00) 실행 */
  EVERY_DAY_AT_MIDNIGHT = '0 0 * * *',

  /** 매일 정오 (12:00) 실행 */
  EVERY_DAY_AT_NOON = '0 12 * * *',

  /** 매주 일요일 자정 실행 */
  EVERY_WEEK = '0 0 * * 0',

  /** 매월 1일 자정 실행 */
  EVERY_MONTH = '0 0 1 * *',

  /** 매년 1월 1일 자정 실행 */
  EVERY_YEAR = '0 0 1 1 *',
}
